"""
Reconcile and segregate all candidates across pilot (82), expansion (21), adjudication (39), and targeted expansion (11).
Outputs:
- backend/data/dataset/candidates_auto_validated.csv
- backend/data/dataset/candidates_needs_review.csv
- backend/data/dataset/candidates_rejected.csv
"""
import csv
import json
from datetime import datetime
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# 1. Load pilot results (82)
with open(REPO_ROOT / "backend/data/dataset/auto_validation_results.csv", encoding="utf-8") as f:
    pilot_rows = {r["candidate_id"]: r for r in csv.DictReader(f)}

# 2. Load multilingual expansion results (21)
with open(REPO_ROOT / "backend/data/dataset/multilingual_expansion_results.csv", encoding="utf-8") as f:
    multi_rows = {r["candidate_id"]: r for r in csv.DictReader(f)}

# 3. Load adjudication results (39)
with open(REPO_ROOT / "backend/data/dataset/adjudication_39_results.csv", encoding="utf-8") as f:
    adj_rows = {r["candidate_id"]: r for r in csv.DictReader(f)}

# Build canonical dictionary of candidates
all_cands = {}

for qid, r in pilot_rows.items():
    cand = dict(r)
    cand["pool"] = "pilot_82"
    all_cands[qid] = cand

for qid, r in multi_rows.items():
    cand = dict(r)
    cand["pool"] = "multilingual_21"
    all_cands[qid] = cand

# Apply adjudication decisions for adjudicated pilot & expansion subset
for qid, adj in adj_rows.items():
    if qid in all_cands:
        cand = all_cands[qid]
        cand["final_status"] = adj["final_status"]
        cand["adjudicator_model"] = adj.get("verifier_c_model", "gemma:2b")
        cand["adjudicator_verdict"] = adj.get("verifier_c_verdict", "")
        cand["adjudication_issues"] = adj.get("issues", "")
        if adj.get("failure_categories"):
            cand["failure_categories"] = adj["failure_categories"]

# Apply strict generator independence and linguistic adjustments:
# 1. Pilot candidates: Generator was gemma:2b. Qwen and Llama are independent.
# fe70960c was demoted to needs_review awaiting human confirmation of Clause 16.1 (vi) correction.
if "fe70960c-f447-4fd4-88c7-20572e422fb0" in all_cands:
    all_cands["fe70960c-f447-4fd4-88c7-20572e422fb0"]["final_status"] = "needs_review"
    all_cands["fe70960c-f447-4fd4-88c7-20572e422fb0"]["issues"] = "Demoted from auto_validated to needs_review awaiting human confirmation of Clause 16.1 (vi) correction"

# 2. Expansion candidates generated by llama3.2:3b (22c565e2, 56ea6e89):
# Llama's acceptance cannot count (generator self-verification). Qwen (REJECT) and Gemma (ACCEPT) disagreed.
if "22c565e2-407b-471a-a3c0-ca059f3400c3" in all_cands:
    all_cands["22c565e2-407b-471a-a3c0-ca059f3400c3"]["final_status"] = "needs_review"
    all_cands["22c565e2-407b-471a-a3c0-ca059f3400c3"]["issues"] = "Generator independence: llama3.2:3b generated candidate; independent verifiers Qwen (REJECT) and Gemma (ACCEPT) disagreed"

if "56ea6e89-aeaf-45e7-9a07-f8a23d132893" in all_cands:
    all_cands["56ea6e89-aeaf-45e7-9a07-f8a23d132893"]["final_status"] = "needs_review"
    all_cands["56ea6e89-aeaf-45e7-9a07-f8a23d132893"]["issues"] = "Generator independence: llama3.2:3b generated candidate; independent verifiers Qwen (REJECT) and Gemma (ACCEPT) disagreed"

# 3. Expansion candidates generated by qwen2.5:3b:
# 14ae71ae ("स्पेन्ट्रेटिव एम्सिप्लीज़"): demote to needs_review
if "14ae71ae-593b-4ff9-831d-77279cb1db1c" in all_cands:
    all_cands["14ae71ae-593b-4ff9-831d-77279cb1db1c"]["final_status"] = "needs_review"
    all_cands["14ae71ae-593b-4ff9-831d-77279cb1db1c"]["issues"] = "Linguistic defect: unnatural transliteration ('स्पेन्ट्रेटिव एम्सिप्लीज़' for supplementary exam)"

# 8d3de1e5 ("मेडिकल कॉस्टर"): demote to needs_review
if "8d3de1e5-0c4a-4db7-9bea-5be2d6dde9be" in all_cands:
    all_cands["8d3de1e5-0c4a-4db7-9bea-5be2d6dde9be"]["final_status"] = "needs_review"
    all_cands["8d3de1e5-0c4a-4db7-9bea-5be2d6dde9be"]["issues"] = "Linguistic defect: unnatural transliteration ('मेडिकल कॉस्टर')"

# dd359bb2: demoted to needs_review due to "बैठने के लिए" imprecision
if "dd359bb2-a9ab-48d1-a231-77c1a9e13455" in all_cands:
    all_cands["dd359bb2-a9ab-48d1-a231-77c1a9e13455"]["final_status"] = "needs_review"
    all_cands["dd359bb2-a9ab-48d1-a231-77c1a9e13455"]["issues"] = "Semantic imprecision: question 'बैठने के लिए न्यूनतम कितनी अटेंडेंस होनी चाहिए?' is ambiguous/incomplete (implies exam sitting without specification); requires qualification to course attendance"

# 4. Load targeted expansion results (if present)
targeted_path = REPO_ROOT / "backend/data/dataset/targeted_expansion_results.csv"
if targeted_path.exists():
    with open(targeted_path, encoding="utf-8") as f:
        targeted_rows = {r["candidate_id"]: r for r in csv.DictReader(f)}
    for qid, r in targeted_rows.items():
        cand = dict(r)
        cand["pool"] = "targeted_11"
        all_cands[qid] = cand

# Segregate into 3 lists
auto_validated = []
needs_review = []
auto_rejected = []

for qid, c in all_cands.items():
    st = c["final_status"]
    if st == "auto_validated":
        auto_validated.append(c)
    elif st == "needs_review":
        needs_review.append(c)
    else:
        auto_rejected.append(c)

print(f"Segregation Summary ({len(all_cands)} total):")
print(f"  auto_validated: {len(auto_validated)}")
print(f"  needs_review:   {len(needs_review)}")
print(f"  auto_rejected:  {len(auto_rejected)}")
assert len(auto_validated) + len(needs_review) + len(auto_rejected) == len(all_cands)

# Export files
fieldnames = [
    "candidate_id", "original_question", "query_language", "query_script",
    "question_type", "answerability", "final_status", "deterministic_passed",
    "verifier_a_verdict", "verifier_b_verdict", "adjudicator_verdict",
    "failure_categories", "issues", "reference_answer", "source_document_id",
    "pool", "timestamp"
]

def export_csv(data, filename):
    p = REPO_ROOT / "backend/data/dataset" / filename
    with open(p, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(data)
    print(f"Saved {len(data)} rows to {p.name}")

export_csv(auto_validated, "candidates_auto_validated.csv")
export_csv(needs_review, "candidates_needs_review.csv")
export_csv(auto_rejected, "candidates_rejected.csv")
