def test_08_citation_with_incorrect_page_number(sample_passages, doc_map):
    """8. Citation with incorrect page number preserves authoritative passage page and records mismatch."""
    p1 = sample_passages[0]
    # Cited as page 99, but actual passage page is 1
    text = f"The minimum attendance is 75% [Source: {p1.passage_id}, page 99]."
    citations, cleaned = _extract_citations_from_text(text, sample_passages, doc_map)
    assert len(citations) == 1
    assert citations[0].page == 1  # Authoritative corpus page preserved
    assert citations[0].page_verified is False
    assert citations[0].cited_page == 99


def test_09_multiple_citations_in_one_answer(sample_passages, doc_map):
    """9. Multiple citations in one answer."""
    p1 = sample_passages[0]
    p2 = sample_passages[1]
    text = (
        f"For semester exams, 75% is required [Source: {p1.passage_id}, page 1]. "
        f"To avoid an X grade, 70% is required [Source: passage_id={p2.passage_id}, page 24]."
    )
    citations, cleaned = _extract_citations_from_text(text, sample_passages, doc_map)
    assert len(citations) == 2
    pids = [c.passage_id for c in citations]
    assert p1.passage_id in pids
    assert p2.passage_id in pids
    assert "[Source:" not in cleaned


def test_10_duplicate_citations(sample_passages, doc_map):
    """10. Duplicate citations are deduplicated."""
    p1 = sample_passages[0]
    text = (
        f"75% attendance is required [Source: {p1.passage_id}, page 1]. "
        f"As stated earlier, exams require 75% [Source: {p1.passage_id}, page 1]."
    )
    citations, cleaned = _extract_citations_from_text(text, sample_passages, doc_map)
    assert len(citations) == 1
    assert citations[0].passage_id == p1.passage_id


def test_11_malformed_citation_syntax(sample_passages, doc_map):
    """11. Malformed citation syntax."""
    p1 = sample_passages[0]
    texts = [
        f"Attendance is 75% (Source: {p1.passage_id}, page 1).",  # parentheses instead of brackets
        f"Attendance is 75% [Source: ].",                          # empty
        f"Attendance is 75% [Source: passage_id].",                # literal keyword without id
    ]
    for t in texts:
        citations, _ = _extract_citations_from_text(t, sample_passages, doc_map)
        assert len(citations) == 0


def test_12_answer_with_no_citations(sample_passages, doc_map):
    """12. Answer with no citations returns empty citations list."""
    text = "The minimum attendance required for examinations is 75%."
    citations, cleaned = _extract_citations_from_text(text, sample_passages, doc_map)
    assert len(citations) == 0
    assert cleaned == text


def test_13_citation_with_unsupported_claim(sample_passages, doc_map):
    """13. Citation referring to a valid passage but unsupported claim."""
    p1 = sample_passages[0]
    # The claim contains a contradiction/hallucination: students can have 20% attendance
    contradicted_claim_text = f"Students only need 20% attendance to pass everything [Source: {p1.passage_id}, page 1]."
    
    mock_claim_res = MagicMock()
    mock_claim_res.contains_contradiction = True
    mock_claim_res.grounding_ratio = 0.0
    mock_claim_res.total_claims = 1

    with patch("app.generation.claim_grounding.get_claim_grounding_verifier") as mock_get_verifier:
        mock_verifier = MagicMock()
        mock_verifier.verify_claims.return_value = mock_claim_res
        mock_get_verifier.return_value = mock_verifier

        citations, _, claim_res = _extract_citations_and_claims(
            contradicted_claim_text, sample_passages, doc_map
        )

    assert len(citations) == 1
    # Syntax is valid, but claim_supported is False!
    assert citations[0].claim_supported is False


def test_14_citation_formatting_variations_ollama(sample_passages, doc_map):
    """14. Citation formatting variations generated by local Ollama models."""
    p1 = sample_passages[0]
    variations = [
        f"Attendance is 75% [Source: passage_id: {p1.passage_id}, page 1].",
        f"Attendance is 75% [Source: passage_id={p1.passage_id}, p. 1].",
        f"Attendance is 75% [Source: {p1.passage_id} , page 1 ].",
        f"Attendance is 75% [Source: passage_id = {p1.passage_id}].",
        f"Attendance is 75% [SOURCE: {p1.passage_id}, PAGE 1].",
    ]
    for v in variations:
        citations, cleaned = _extract_citations_from_text(v, sample_passages, doc_map)
        assert len(citations) == 1, f"Failed for variation: {v}"
        assert citations[0].passage_id == p1.passage_id
        assert "[Source:" not in cleaned.lower()
